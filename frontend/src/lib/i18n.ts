// ------------------------------------------------------------------ server messages
// The domain speaks English; French readers get the same message in their language.

const serverFr: [RegExp, (m: RegExpMatchArray) => string][] = [
  [/^There is no table with code (.+)$/, (m) => `Aucune table ne porte le code ${m[1]}`],
  [/^'(.+)' is not a card in this deck$/, (m) => `« ${m[1]} » ne fait pas partie de ce jeu`],
  [/^'(.+)' is not a valid table code$/, (m) => `« ${m[1]} » n’est pas un code de table valide`],
  [/^Nobody sits there$/, () => 'Cette place est vide'],
  [/^That effect is not in the box$/, () => 'Cet effet n’existe pas'],
  [/^That person is not seated at this table$/, () => 'Cette personne n’est pas à cette table'],
  [/^That story is not on this table$/, () => 'Cette story n’est pas sur cette table'],
  [/^There is no story in play$/, () => 'Aucune story n’est en jeu'],
  [/^Unknown deck '(.+)'$/, (m) => `Jeu de cartes inconnu « ${m[1]} »`],
  [/^Unknown participant$/, () => 'Participant inconnu'],
  [/^Unknown role '(.+)'$/, (m) => `Rôle inconnu « ${m[1]} »`],
  [/^Unknown story$/, () => 'Story inconnue'],
  [/^Voting is not open right now$/, () => 'Le vote n’est pas ouvert pour le moment'],
  [/^Observers watch the game; switch to voter to play cards$/, () => 'Les observateurs regardent la partie ; passez en mode votant pour jouer'],
  [/^Only the facilitator can do that$/, () => 'Seul le facilitateur peut faire cela'],
  [/^You are not seated at this table$/, () => 'Vous n’êtes pas installé à cette table'],
  [/^Take a seat first$/, () => 'Prenez d’abord place à la table'],
  [/^The table was busy, please try again$/, () => 'La table était occupée, veuillez réessayer'],
  [/^(.+) cannot be blank$/, (m) => `${m[1]} : ce champ ne peut pas être vide`],
  [/^(.+) is required$/, (m) => `${m[1]} : ce champ est obligatoire`],
  [/^(.+) must be at most (\d+) characters$/, (m) => `${m[1]} : ${m[2]} caractères maximum`],
];

export function localizeServerMessage(message: string): string {
  if (locale !== 'fr') return message;
  for (const [pattern, render] of serverFr) {
    const match = message.match(pattern);
    if (match) return render(match);
  }
  return message;
}
