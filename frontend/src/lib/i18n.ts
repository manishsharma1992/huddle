/**
 * Tiny i18n: English and French, chosen once from the browser's preferred languages.
 * Strings are plain values or functions (for interpolation and plurals), so every key is type-checked
 * and the French dictionary can't silently miss one.
 */

export type Locale = 'en' | 'fr';

function detectLocale(): Locale {
  const preferred = typeof navigator === 'undefined' ? [] : navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const tag of preferred) {
    const lang = tag?.toLowerCase().split('-')[0];
    if (lang === 'fr') return 'fr';
    if (lang === 'en') return 'en';
  }
  return 'en';
}

